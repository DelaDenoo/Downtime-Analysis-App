SHAPE = 1.0 / DURATION_CV**2


def estimate_block_size(daily_hours, max_lag=60):
    """Block length (days) at which the autocorrelation first falls inside its 95% band."""
    values = daily_hours.dropna().to_numpy()
    max_lag = min(max_lag, len(values) - 1)
    centered = values - values.mean()
    acf = (
        np.array([(centered[:-lag] * centered[lag:]).sum() for lag in range(1, max_lag + 1)])
        / (centered**2).sum()
    )
    threshold = 1.96 / np.sqrt(len(values))
    inside = np.flatnonzero(np.abs(acf) < threshold)
    return max(inside[0] + 1 if inside.size else max_lag, 1), acf, threshold


def verdict(actual, p10, p90):
    return 'Better' if actual < p10 else ('Worse' if actual > p90 else 'Within range')


