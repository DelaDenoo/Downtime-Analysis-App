def safe_filename(text):
    return re.sub(r'[^A-Za-z0-9]+', '_', str(text)).strip('_')


def short_name(unit):
    """'PR1: PR1' -> 'PR1', 'Roaster (RO201)' -> 'Roaster', 'Liquor Moulding: TM41' -> 'TM41'."""
    if ':' in unit:
        return unit.split(':')[-1].strip()
    return unit.split(' (')[0].strip()


def hours_days(hours, decimals=1):
    """'120.0 h (5.0 d)': an hours figure with its day equivalent (one day = 24 hours)."""
    return f'{hours:,.{decimals}f} h ({days_text(hours)})'


def days_text(hours):
    days = hours / 24
    return (
        f'{days:,.0f} d'
        if abs(days) >= 10
        else f'{days:,.1f} d' if abs(days) >= 1 or days == 0 else f'{days:,.2f} d'
    )


def day_ticks(ax, axis='x'):
    """Axis tick labels with the hours on the first line and the day equivalent (hours / 24) underneath."""
    (ax.xaxis if axis == 'x' else ax.yaxis).set_major_formatter(
        FuncFormatter(lambda value, _position: f'{value:,.0f} h\n{days_text(value)}')
    )


def use_symlog_x(ax, max_value):
    """Symlog x axis (zero allowed) with hours and day-equivalent ticks."""
    ax.set_xscale('symlog', linthresh=1)
    ax.set_xticks([t for t in (0, 1, 10, 100, 1000, 10000) if t <= max_value * 1.5])
    day_ticks(ax, 'x')


