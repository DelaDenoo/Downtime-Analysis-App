MAX_STORED = 8


@st.cache_resource
def _store():
    """Finished analyses, shared by this server process. Newest last; the oldest drop out."""
    return {}


def _key(line, data, options):
    return (line, hashlib.sha1(data).hexdigest(), tuple(sorted(options.items())))


def _remember(key, analysis):
    store = _store()
    store[key] = analysis
    while len(store) > MAX_STORED:
        store.pop(next(iter(store)))


def _run(line, data, name, options, holder):
    key = _key(line, data, options)
    cached = _store().get(key)
    if cached is not None:
        return key, cached
    bar = holder.progress(0.0, text='Starting')
    try:
        analysis = runner.run_line(line, data, name, options, progress=lambda f, label: bar.progress(min(f, 1.0), text=label))
    except Exception as error:
        bar.empty()
        holder.markdown(C.callout(
            f'The file opened, but the layout for {line} was not found. Check that it is the daily and reason log workbook for this line, '
            f'with the same sheet names and columns as before. (Detail: {type(error).__name__}: {error})', title='This workbook could not be read', tone='warn'), unsafe_allow_html=True)
        with holder.expander('Technical detail'):
            st.code(traceback.format_exc())
        return key, None
    bar.empty()
    _remember(key, analysis)
    return key, analysis


