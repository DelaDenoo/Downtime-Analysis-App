def assign_theme(reasons, patterns):
    theme = pd.Series(np.nan, index=reasons.index, dtype=object)
    for name in reversed(list(patterns)):
        theme[match_any(reasons, patterns[name])] = name
    return theme


def assign_themes(reasons, patterns, rules):
    """Theme per reason. Vague wording overrides: 'unknown' anywhere is Unknown, Minor stops keep their own theme."""
    theme = assign_theme(reasons, patterns)
    theme[match_any(reasons, rules['not_clear'])] = NOT_CLEAR_THEME
    theme[match_any(reasons, UNKNOWN_REASON_PATTERNS + [r'\bunknown\b'])] = UNKNOWN_THEME
    theme[match_any(reasons, [MINOR_STOPS_PATTERN])] = MINOR_THEME
    return theme


def build_theme_setup(cfg, rules):
    """(unit libraries, shared-first themes) for a line. Own libraries come from `cfg['themes']`
    ('default' for units without an entry); COMMON_THEMES are added to every one."""
    shared_first = {
        'Material Supply Shortage': rules['supply'],
        **SHARED_FIRST_BASE,
        **cfg.get('shared_first_extra', {}),
        'Waiting for Another Unit': rules['waiting'],
    }
    libraries = cfg['themes']
    unit_libs = {
        unit: extend(libraries.get(unit, libraries['default']), COMMON_THEMES)
        for unit in cfg['log_cols']
    }
    for lib in [shared_first, PLANNED_THEMES, *unit_libs.values()]:
        assert all(
            re.compile(p).groups == 0 for ps in lib.values() for p in ps
        ), 'use (?: ) in patterns'
    return unit_libs, shared_first


def themed_log(L, log, unit):
    """Whole reason log with a Theme column. Planned rows get 'Planned: <theme>'; nothing is dropped."""
    is_unplanned = log['Class'] == 'Unplanned loss'
    unplanned = assign_themes(
        log.loc[is_unplanned, 'Reason'], {**L.shared_first, **L.unit_libs[unit]}, L.rules
    )
    planned = assign_themes(log.loc[~is_unplanned, 'Reason'], PLANNED_THEMES, L.rules)
    theme = pd.concat([unplanned.fillna(NO_THEME), 'Planned: ' + planned.fillna(NO_THEME)])
    return log.assign(Theme=theme.reindex(log.index))

