def report_own_vs_attributed(L):
    """Two views of each unit's downtime: the reference unit's reasons attributed to it, and the unit's own log."""
    if not L.reference:
        print(
            f'{L.name} has no reference unit whose comments name other units, so there is '
            f'no attribution to compare '
            "with the units' own logs. Each headline unit's own log is the only view."
        )
        return
    A = L.attribution
    sources = A['labels'] + ['Minor stops', 'Unknown', 'Multiple units mentioned', 'Unattributable']
    own_label = A['unit_label']
    hours_rows, share_rows, waiting_rows = {}, {}, {}
    for unit in L.logged:
        tagged = with_source(L, L.logs[unit])
        unplanned = tagged[tagged['Class'] == 'Unplanned loss']
        downtime = L.dfs[unit]['Duration (hours)'].sum()
        window_unplanned = scaled_class_hours(L.logs[unit], downtime)['Unplanned loss']
        by_source = (
            unplanned.groupby('Allocated_To')['Duration_hours']
            .sum()
            .reindex(sources, fill_value=0.0)
        )
        assert np.isclose(
            by_source.sum(), unplanned['Duration_hours'].sum()
        ), f'{unit}: reasons lost in attribution'
        total = by_source.sum()
        share_rows[unit] = by_source / total * 100 if total else by_source
        hours_rows[unit] = by_source / total * window_unplanned if total else by_source
        waiting_rows[unit] = (
            L.logs[unit].loc[L.logs[unit]['Waiting'], 'Duration_hours'].sum()
            / L.logs[unit]['Duration_hours'].sum()
            * downtime
        )
    own_hours, own_share = pd.DataFrame(hours_rows).T, pd.DataFrame(share_rows).T
    summary = pd.DataFrame(
        {
            'Own unplanned (hrs, window)': own_hours.sum(axis=1),
            'Points to itself (%)': [own_share.loc[u, own_label[u]] for u in L.logged],
            'Points to another unit (%)': [
                own_share.loc[u, [x for x in A['labels'] if x != own_label[u]]].sum()
                for u in L.logged
            ],
            'Minor stops (%)': own_share['Minor stops'],
            'Unknown (%)': own_share['Unknown'],
            'Multiple units (%)': own_share['Multiple units mentioned'],
            'Unattributable (%)': own_share['Unattributable'],
        }
    )
    assert np.allclose(
        summary.iloc[:, 1:].sum(axis=1), 100
    ), 'shares must add to 100 for every unit'
    print('##### PART C. The Roaster comments and the units\' own logs, side by side.')
    print(
        "C1. The units' OWN logs run through the same unit keywords used for the Roaster comments."
    )
    print("Share of each unit's own unplanned reasons, by the unit the wording points to (%):")
    display(own_share.round(1))
    print('Summary (hours scaled to the window):')
    display(summary.round(1))

    fig, ax = plt.subplots(figsize=(11, 0.7 * len(L.logged) + 2.5))
    image = ax.imshow(
        own_share.to_numpy(dtype=float), cmap='Blues', vmin=0, vmax=100, aspect='auto'
    )
    ax.set_xticks(range(len(sources)), sources, rotation=40, ha='right')
    ax.set_yticks(range(len(L.logged)), [L.short[u] for u in L.logged])
    for i, unit in enumerate(L.logged):
        for j, source in enumerate(sources):
            value = own_share.loc[unit, source]
            if value >= 1:
                ax.text(
                    j,
                    i,
                    f'{value:.0f}',
                    ha='center',
                    va='center',
                    fontsize=8,
                    color='white' if value > 55 else 'black',
                )
    ax.grid(False)
    ax.set_xlabel('Unit the reason wording points to')
    ax.set_ylabel('Log the reason came from')
    ax.set_title(
        "OWN LOGS: where each unit's own unplanned reasons point (% of its unplanned hours)",
        fontsize=11,
    )
    fig.colorbar(image, ax=ax, label='% of unplanned hours')
    fig.tight_layout()
    safe_savefig(fig, f'{L.tag}_C_own_logs_keyword_matrix')
    plt.show()

    # Two views side by side, in hours of the window. A source that several units share (Grinding)
    # adds their logs.
    M_ref = (
        L.metrics[L.reference]
        if hasattr(L, 'metrics') and L.reference in L.metrics
        else compute_metrics(L, L.reference)
    )
    attributed = (
        L.attributed_log[L.attributed_log['Class'] == 'Unplanned loss']
        .groupby('Allocated_To')['Duration_hours']
        .sum()
    )
    attributed_window = attributed / attributed.sum() * M_ref.unplanned
    rows = []
    for label in A['labels']:
        units = [u for u in L.logged if own_label[u] == label]
        own = float(own_hours.loc[units].sum().sum())
        waiting = float(sum(waiting_rows[u] for u in units))
        via = float(attributed_window.get(label, 0.0))
        rows.append(
            {
                'Source': label,
                f'From {L.short[L.reference]} COMMENTS (hrs)': via,
                "From the unit's OWN log, unplanned (hrs)": own,
                'of which waiting (hrs)': waiting,
                'Own log / Roaster comments': own / via if via > 0 else np.nan,
            }
        )
    views = pd.DataFrame(rows)
    print(
        f'C2. Two views in hours of each log\'s own window: what the {L.short[L.reference]} '
        f'COMMENTS blame on a unit, '
        "against that unit's OWN log."
    )
    print(f'"{A["own_label"]}" is the reference unit against itself.')
    display(views.round(1))
    fig, ax = plt.subplots(figsize=(11, 0.6 * len(views) + 2.5))
    y = np.arange(len(views))
    ax.barh(
        y - 0.2,
        views[f'From {L.short[L.reference]} COMMENTS (hrs)'],
        height=0.38,
        color=COLOR['warn'],
        label=f'From the {L.short[L.reference]} COMMENTS blamed on the unit',
    )
    ax.barh(
        y + 0.2,
        views["From the unit's OWN log, unplanned (hrs)"],
        height=0.38,
        color=COLOR['unit'],
        label="From the unit's OWN log",
    )
    ax.set_yticks(y, views['Source'])
    ax.invert_yaxis()
    use_symlog_x(ax, views.iloc[:, 1:3].to_numpy().max())
    ax.set_xlabel('Unplanned hours in the window (symlog scale; days = hours / 24)')
    ax.legend(loc='upper center', bbox_to_anchor=(0.5, -0.18), ncol=2)
    ax.set_title(
        "Same unit, two different logs: the reference unit's COMMENTS (orange) versus the "
        "unit's OWN log (blue)",
        fontsize=11,
    )
    fig.tight_layout()
    safe_savefig(fig, f'{L.tag}_C_two_views')
    plt.show()
    print(
        'What: each row compares the reference unit\'s reasons blamed on a unit with that '
        'unit\'s own log.'
    )
    print(
        'Limit: the keyword rules were written for the reference unit\'s wording. A unit\'s '
        'own fault that never names'
    )
    print(
        'the unit (for example "bearing failure") lands in Unattributable, so "points to '
        'another unit" is a lower bound.'
    )
    print(
        'The own log also holds waiting and knock-on stops, so it is not a clean measure of '
        'the unit\'s own faults.'
    )
    L.results.update(C_own_log_keywords=own_share.reset_index(), C_two_views=views)

