def finish_log(raw, rules, block_cut=False):
    """Tidy reason log (Category, Reason, Duration_hours, Count) with its wording-based class and waiting flag."""
    raw = raw.copy()
    raw['Category'] = raw['Category'].replace(r'^\s*$', np.nan, regex=True).ffill()
    raw['Reason'] = raw['Reason'].replace(r'^\s*$', np.nan, regex=True)
    log = raw.dropna(subset=['Reason']).copy()
    log[['Duration_hours', 'Count']] = log[['Duration_hours', 'Count']].apply(
        pd.to_numeric, errors='coerce'
    )
    no_hours = int(log['Duration_hours'].isna().sum())
    log = log.dropna(subset=['Duration_hours'])[['Category', 'Reason', 'Duration_hours', 'Count']]
    reason = log['Reason'].astype(str)
    log = log.assign(Reason=reason, Class=classify_by_wording(reason, rules)).reset_index(drop=True)
    log['Count'] = log['Count'].fillna(0.0)
    log['Waiting'] = match_any(log['Reason'], rules['waiting']) & (log['Class'] == 'Unplanned loss')
    log.attrs.update(no_hours=no_hours, block_cut_at_row_limit=block_cut)
    return log


def read_log_from_columns(book, col_letters, skiprows, rules, sheet=0):
    raw = book.parse(
        sheet_name=sheet,
        usecols=col_letters,
        skiprows=skiprows,
        header=None,
        nrows=LOG_MAX_ROWS,
        names=LOG_COLUMNS,
    )
    return finish_log(
        raw,
        rules,
        block_cut=bool(len(raw) >= LOG_MAX_ROWS and raw['Reason'].iloc[-1:].notna().any()),
    )


