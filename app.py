        if len(train) < MIN_TRAINING_DAYS:
            print(
                f'{L.short[unit]}: only {len(train)} days would be left to learn from, '
                f'backtest skipped.'
            )
            continue
        history = build_history(L, unit, train)
        hold_hours = hold['Duration (hours)'].sum()
        actual = scaled_class_hours(L.logs[unit], hold_hours)
        log = L.logs[unit]
        actual_waiting = (
            log.loc[log['Waiting'], 'Duration_hours'].sum()
            / log['Duration_hours'].sum()
            * hold_hours
        )
