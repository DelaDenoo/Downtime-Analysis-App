def check_config(cfg):
    units = list(cfg['daily'])
    assert cfg['headline'], 'give at least one headline unit'
    for key, group in {
        'log_cols': cfg['log_cols'],
        'headline': cfg['headline'],
        'integrity': list(cfg.get('integrity', {})),
    }.items():
        missing = [unit for unit in group if unit not in units]
        assert not missing, f'{key}: {missing} are not in the daily columns'
    assert all(
        unit in cfg['log_cols'] for unit in cfg['headline']
    ), 'every headline unit needs a reason log'
    assert 'default' in cfg['themes'], "cfg['themes'] needs a 'default' library"
    if cfg.get('reference'):
        assert cfg['reference'] in cfg['headline'] and cfg.get(
            'attribution'
        ), 'a reference unit needs attribution settings'
        assert set(cfg['log_cols']) == set(
            units
        ), 'with attribution every unit needs its own reason log'
        A = cfg['attribution']
        assert set(A['equipment_patterns']) == set(A['labels']) - {
            A['own_label']
        }, 'equipment_patterns must cover every label but its own'
        assert set(A['unit_label']) == set(units) and set(A['unit_label'].values()) <= set(
            A['labels']
        ), 'every unit needs a label'
        assert A['supply_label'] in A['labels'], 'supply_label must be one of the labels'
        assert all(
            re.compile(p).groups == 0
            for ps in [
                *A['equipment_patterns'].values(),
                A['own_keywords'],
                [A['named_unit_pattern']],
            ]
            for p in ps
        ), 'use (?: ) in attribution patterns'


def load_line(cfg):
    """Read one line's workbook and return the objects every report below works from."""
    check_config(cfg)
    rules = make_rules(cfg.get('rules_extra'))
    units = list(cfg['daily'])
    sheet = cfg.get('sheet') or 0
    logged = [unit for unit in units if unit in cfg['log_cols']]

    with pd.ExcelFile(cfg['file']) as book:
        daily_full = {
            unit: read_daily(book, sheet=sheet, **spec) for unit, spec in cfg['daily'].items()
        }

    discovered = {}
    if DISCOVER_LOG_BLOCKS:
        try:
            discovered, _ = discover_category_blocks(cfg['file'], cfg.get('sheet'))
        except (
            Exception
        ) as error:  # discovery is a convenience, the configured columns are the fallback
            print(
                f'{cfg["name"]}: reason-block discovery failed ({type(error).__name__}: {error}); '
                'using the configured columns for every unit.'
            )
    logs, log_source = {}, {}
    with pd.ExcelFile(cfg['file']) as book:
        for unit in logged:
            block = resolve_unit_block(unit, discovered)
            raw = (
                load_discovered_block(cfg['file'], block, cfg.get('sheet'))
                if block is not None
                else None
            )
            if raw is not None and len(raw):
                logs[unit] = finish_log(raw, rules)
                letters = sorted(block['columns'].values(), key=column_index_from_string)
                log_source[unit] = (
                    f'found by header text: row {block["header_row"]}, columns {letters[0]} '
                    f'to {letters[-1]}'
                )
            else:
                logs[unit] = read_log_from_columns(
                    book, cfg['log_cols'][unit], cfg['log_skiprows'], rules, sheet
                )
                log_source[unit] = (
                    f'configured columns {cfg["log_cols"][unit]}, skip {cfg["log_skiprows"]} rows'
                )

    def in_window(daily):
        if not cfg.get('exclude_march'):
            return daily
        return daily[~daily['Date'].between(cfg['march_start'], cfg['march_end'])].reset_index(
            drop=True
        )

    unit_libs, shared_first = build_theme_setup(cfg, rules)
    short = {unit: cfg.get('short', {}).get(unit, short_name(unit)) for unit in units}
    palette = iter(UNIT_PALETTE)
    colors = {unit: cfg.get('colors', {}).get(unit) or next(palette) for unit in units}
    return SimpleNamespace(
        cfg=cfg,
        name=cfg['name'],
        tag=cfg['tag'],
        rules=rules,
        units=units,
        logged=logged,
        headline=list(cfg['headline']),
        reference=cfg.get('reference'),
        attribution=cfg.get('attribution'),
        daily_full=daily_full,
        dfs={unit: in_window(daily) for unit, daily in daily_full.items()},
        logs=logs,
        log_source=log_source,
        unit_libs=unit_libs,
        shared_first=shared_first,
        short=short,
        colors=colors,
        results={},
    )

