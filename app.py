VAGUE_STOPS = [
    UNKNOWN_THEME,
    NOT_CLEAR_THEME,
    MINOR_THEME,
    NO_THEME,
    'Unattributable',
    'Multiple units mentioned',
]
GROUP_COLORS = [COLOR['headline'], COLOR['warn'], COLOR['unit']]


def beta_for(unit):
    return float(WEIBULL_BETA_BY_UNIT.get(unit, WEIBULL_BETA))


def run_scale(beta):
    return gamma_function(1 + 1 / beta)


def hazard_coef(stops, bases, beta):
    """c in  chance of running t hours without the stop = exp(-c * t ** beta).
    For one cause with `stops` stops over `bases` hours, c = (1 / eta) ** beta with eta = (bases / stops) / Gamma(1 + 1 / beta).
    Causes acting together: their c values add, which is the same as multiplying their curves."""
    stops, bases = np.asarray(stops, dtype=float), np.asarray(bases, dtype=float)
    if np.any(bases <= 0):
        return np.nan
    return float(np.sum((stops * run_scale(beta) / bases) ** beta))


def survival(t, c, beta):
    return np.exp(-c * np.asarray(t, dtype=float) ** beta)


def median_run(c, beta):
    return (np.log(2) / c) ** (1 / beta)


def time_at_level(c, beta, level):
    """Running time at which the chance of still running has fallen to `level`."""
    return (-np.log(level) / c) ** (1 / beta)


def coef_range(stops, base, beta):
    """(low, high) of c when the stop counts are uncertain: each count is treated as a Poisson rate seen once,
    so its rate varies as Gamma(count) / count. Few stops give a wide range, many stops a narrow one.
    """
    stops = np.asarray(stops, dtype=float)
    if base <= 0 or stops.size == 0:
        return np.nan, np.nan
    rng = np.random.default_rng(SEED)
    spread = rng.gamma(shape=stops, scale=1.0 / stops, size=(BAND_DRAWS, stops.size))
    draws = ((spread * stops * run_scale(beta) / base) ** beta).sum(axis=1)
    return np.percentile(draws, BAND[0]), np.percentile(draws, BAND[1])


def fit_weibull_beta(daily_hours):
    """Shape fitted to gaps between above-median downtime days; (None, reason) if unreliable."""
    values = daily_hours.dropna().to_numpy()
    if (values > 0).sum() < 10:
        return None, 'fewer than 10 days with downtime'
    gaps = np.diff(np.flatnonzero(values > np.median(values[values > 0])))
    if len(gaps) < 10 or gaps.std() < 1e-6:
        return None, 'too few or too uniform gaps between bad days'
    beta = stats.weibull_min.fit(gaps, floc=0)[0]
    return (beta, None) if 0.1 < beta < 20 else (None, f'fitted shape {beta:.1f} is implausible')


def evidence_label(stops, base):
    if base <= 0:
        return 'CHECK: no running time left'
    return f'Thin ({stops:.0f} stops)' if stops < MIN_STOPS_FOR_CURVE else 'OK'


def range_text(low, high):
    return f'{low:,.0f} to {high:,.0f}' if np.isfinite(low) and np.isfinite(high) else 'n/a'


def weibull_unit(L, unit, view='own'):
    """Weibull numbers for one unit from its reason log.
    view 'own': the unit's own log, causes = themes.  view 'A_attributed' (reference unit only): the unit's comments
    blamed on units, causes = the unit each comment names.
    A STOP is an unplanned reason that is not waiting and not material supply (those are caused elsewhere).
    Planned reasons are never stops. Three time bases are compared:
      Before = log hours minus the cause's own downtime (the original method, planned time still counted as running)
      Planned removed = the same with the unit's planned hours taken out
      After = running time: log hours minus ALL downtime (planned, waiting and every stop)."""
    log = L.logs[unit].reset_index(drop=True)
    if view == 'own':
        log = themed_log(L, log, unit).assign(Cause=lambda t: t['Theme'])
        is_outside = log['Theme'].isin(OUTSIDE_THEMES) | log['Waiting']
    else:
        log = with_source(L, log).assign(Cause=lambda t: t['Allocated_To'])
        is_outside = log['Waiting']
    is_planned = log['Class'] != 'Unplanned loss'
    is_outside = is_outside & ~is_planned
    days = len(L.daily_full[unit])
    calendar = 24.0 * days
    daily_down, log_down = L.daily_full[unit]['Duration (hours)'].sum(), log['Duration_hours'].sum()
    factor = (
        daily_down / log_down if log_down > 0 and np.isfinite(daily_down) else 1.0
    )  # log hours -> measured daily hours
    log_vs_daily = 1 / factor if factor > 0 else np.nan
    hours, count = log['Duration_hours'] * factor, log['Count'] * factor
    planned, outside = hours[is_planned].sum(), hours[is_outside].sum()
    stop_rows = ~is_planned & ~is_outside
    table = (
        pd.DataFrame(
            {
                'Cause': log.loc[stop_rows, 'Cause'],
                'Hours': hours[stop_rows],
                'Stops': count[stop_rows],
            }
        )
        .groupby('Cause', as_index=False)
        .sum()
        .sort_values('Hours', ascending=False)
        .reset_index(drop=True)
    )
    stop_hours = table['Hours'].sum()
    running = calendar - (planned + outside + stop_hours)
    live = table[table['Stops'] > 0].reset_index(drop=True)
    beta = beta_for(unit)

    rows = []
    for _, g in live.iterrows():
        row = {
            'Group': g['Cause'],
            'Kind': 'Vague cause' if g['Cause'] in VAGUE_STOPS else 'Identified cause',
            'Stops': g['Stops'],
            'Hours': g['Hours'],
        }
        for key, base in (
            ('Before', calendar - g['Hours']),
            ('Planned removed', calendar - planned - g['Hours']),
            ('After', running),
        ):
            c = hazard_coef([g['Stops']], base, beta)
            row[f'MTBF {key}'] = base / g['Stops'] if base > 0 else np.nan
            row[f'Median {key}'] = median_run(c, beta)
            row[f'c {key}'] = c
        low, high = coef_range([g['Stops']], running, beta)
        row.update(
            {
                'c After low': low,
                'c After high': high,
                'Median After low': median_run(high, beta),
                'Median After high': median_run(low, beta),
                'Evidence': evidence_label(g['Stops'], running),
            }
        )
        rows.append(row)
    groups = pd.DataFrame(rows)

    fitted, problem = fit_weibull_beta(L.dfs[unit]['Duration (hours)'])
    in_curve = live[~live['Cause'].isin(UNIT_CURVE_LEAVE_OUT)]
    n_stops = in_curve['Stops'].sum()
    summary = {
        'Unit': unit,
        'View': 'own log' if view == 'own' else 'comments blamed on units',
        'Days in log': days,
        'Log / daily hours': log_vs_daily,
        'Own stops': n_stops,
        'Own-stop hrs': stop_hours,
        'Waiting or supply hrs': outside,
        'Planned hrs': planned,
        'Planned (% of log window)': planned / calendar * 100,
        'Running hrs': running,
        'Shape used': beta,
        'Shape fitted': fitted if fitted is not None else np.nan,
    }
    curves = None
    if n_stops > 0:
        c_before = hazard_coef(in_curve['Stops'], calendar - in_curve['Hours'], beta)
        c_planned = hazard_coef(in_curve['Stops'], calendar - planned - in_curve['Hours'], beta)
        c_after = hazard_coef(in_curve['Stops'], running, beta)
        c_low, c_high = coef_range(in_curve['Stops'], running, beta)
        curves = {
            'Before': c_before,
            'Planned removed': c_planned,
            'After': c_after,
            'low': c_low,
            'high': c_high,
        }
        summary.update(
            {
                'MTBF Before (h)': (calendar - stop_hours) / n_stops,
                'MTBF After (h)': running / n_stops if running > 0 else np.nan,
                'Median run Before (h)': median_run(c_before, beta),
                'Median run, planned removed (h)': median_run(c_planned, beta),
                'Median run After (h)': median_run(c_after, beta),
                'Median After low (h)': median_run(c_high, beta),
                'Median After high (h)': median_run(c_low, beta),
                'Evidence': evidence_label(n_stops, running),
            }
        )
        summary['Median change (%)'] = (
            summary['Median run After (h)'] / summary['Median run Before (h)'] - 1
        ) * 100
        for d in PROBABILITY_DAYS:
            summary[f'Runs {d} d without a stop (%)'] = survival(24.0 * d, c_after, beta) * 100
        for b in SHAPE_SENSITIVITY:
            summary[f'Median After, shape {b:g} (h)'] = median_run(
                hazard_coef(in_curve['Stops'], running, b), b
            )
    else:
        summary['Evidence'] = 'No unplanned stops with a count in the log'
    note = []
    if not 0.95 <= log_vs_daily <= 1.05:
        note.append(
            f'the reason log adds up to {log_vs_daily * 100:.0f}% of the daily downtime '
            f'hours, so its hours and counts are rescaled to the daily hours'
        )
    if (table['Stops'] == 0).any():
        note.append(
            f'{table.loc[table["Stops"] == 0, "Hours"].sum():,.0f} h of stops have no count '
            f'and cannot be used'
        )
    return SimpleNamespace(
        unit=unit,
        view=view,
        beta=beta,
        calendar=calendar,
        planned=planned,
        outside=outside,
        stop_hours=stop_hours,
        running=running,
        n=n_stops,
        groups=groups,
        curves=curves,
        summary=summary,
        fitted=fitted,
        fit_problem=problem,
        note='; '.join(note),
    )


