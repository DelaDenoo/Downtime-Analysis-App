def scaled_class_hours(log, downtime):
    """`downtime` split by class, using each class's share of the (undated) reason log."""
    by_class = log.groupby('Class')['Duration_hours'].sum().reindex(CLASSES, fill_value=0.0)
    assert by_class.sum() > 0, 'the reason log has no hours'
    return by_class / by_class.sum() * downtime


def time_split(days, planned_other, planned_maintenance):
    """(time base, planned production time) in hours under PLANNED_MAINTENANCE_HANDLING."""
    calendar_hours = 24.0 * days
    if PLANNED_MAINTENANCE_HANDLING == 'exclude_from_calculation':
        time_base, planned = calendar_hours - planned_maintenance, planned_other
    elif PLANNED_MAINTENANCE_HANDLING == 'planned_stop':
        time_base, planned = calendar_hours, planned_other + planned_maintenance
    else:
        raise ValueError(
            "PLANNED_MAINTENANCE_HANDLING must be 'exclude_from_calculation' or 'planned_stop'"
        )
    if np.any(time_base - planned <= 0):
        raise ValueError('The planned hours leave no planned production time in this period.')
    return time_base, time_base - planned


def availability_pct(unplanned, time_base, planned_production):
    """(Availability, Calendar Availability, Utilization) in %; `unplanned` may be trial arrays."""
    running = planned_production - np.minimum(unplanned, planned_production)
    return (
        running / planned_production * 100,
        running / time_base * 100,
        planned_production / time_base * 100,
    )


def compute_metrics(L, unit, window=None):
    """Window figures of one unit: the reason-log class mix is applied to the window's measured downtime."""
    window = L.dfs[unit] if window is None else window
    days, downtime = len(window), window['Duration (hours)'].sum()
    class_hours = scaled_class_hours(L.logs[unit], downtime)
    unplanned, planned_other, pm = class_hours[CLASSES]
    time_base, planned_production = time_split(days, planned_other, pm)
    calendar_hours = 24.0 * days
    running = calendar_hours - downtime
    availability, calendar_availability, utilization = availability_pct(
        unplanned, time_base, planned_production
    )
    assert (
        abs(running + unplanned + (time_base - planned_production) - time_base) < 1e-6
    ), 'hours do not add up'
    assert abs(availability * utilization / 100 - calendar_availability) < 1e-6
    assert abs(running / time_base * 100 - calendar_availability) < 1e-6
    return SimpleNamespace(
        unit=unit,
        days=days,
        downtime=downtime,
        calendar_hours=calendar_hours,
        class_hours=class_hours,
        unplanned=unplanned,
        planned_other=planned_other,
        pm=pm,
        time_base=time_base,
        planned_production=planned_production,
        planned=time_base - planned_production,
        running=running,
        availability=availability,
        calendar_availability=calendar_availability,
        utilization=utilization,
    )


def availability_if_planned(M, planned_other):
    """(Availability, Utilization) in % if `planned_other` hours of the downtime were planned."""
    base, planned_production = time_split(M.days, planned_other, M.pm)
    result = availability_pct(M.downtime - planned_other - M.pm, base, planned_production)
    return result[0], result[2]


def sensitivity_table(L, unit, M):
    """How far Availability moves if the planned share is wrong or borderline reasons are judged differently."""
    max_planned = M.downtime - M.pm
    scenarios = []
    for shift in (-10, -5, 0, 5, 10):
        raw = M.planned_other + shift / 100 * M.downtime
        planned = float(np.clip(raw, 0, max_planned))
        share = planned / M.downtime * 100 if M.downtime else 0.0
        if planned != raw and any(s['Planned share of downtime (%)'] == share for s in scenarios):
            continue
        label = 'Base' if shift == 0 else f'Planned share {shift:+d} points'
        scenarios.append(
            {
                'Scenario': label if planned == raw else f'{label} (limited to the possible range)',
                'Planned share of downtime (%)': share,
                **dict(
                    zip(
                        ['Availability (%)', 'Utilization (%)'], availability_if_planned(M, planned)
                    )
                ),
            }
        )
    log = L.logs[unit]
    borderline = log[
        match_any(log['Reason'], L.rules['borderline']) & (log['Class'] != 'Planned maintenance')
    ]
    borderline = borderline.groupby(['Reason', 'Class'], as_index=False)['Duration_hours'].sum()
    borderline['window_hours'] = (
        borderline['Duration_hours'] / log['Duration_hours'].sum() * M.downtime
    )
    borderline['direction'] = np.where(borderline['Class'] == 'Unplanned loss', 1.0, -1.0)
    for _, row in borderline.sort_values('Duration_hours', ascending=False).iterrows():
        flipped = float(
            np.clip(M.planned_other + row['direction'] * row['window_hours'], 0, max_planned)
        )
        verb = 'planned' if row['direction'] > 0 else 'unplanned'
        scenarios.append(
            {
                'Scenario': f'{row["Reason"]} counted as {verb}',
                'Planned share of downtime (%)': flipped / M.downtime * 100,
                **dict(
                    zip(
                        ['Availability (%)', 'Utilization (%)'], availability_if_planned(M, flipped)
                    )
                ),
            }
        )
    if len(borderline) > 1:
        flipped_all = float(
            np.clip(
                M.planned_other + (borderline['direction'] * borderline['window_hours']).sum(),
                0,
                max_planned,
            )
        )
        scenarios.append(
            {
                'Scenario': 'All borderline reasons switched',
                'Planned share of downtime (%)': flipped_all / M.downtime * 100,
                **dict(
                    zip(
                        ['Availability (%)', 'Utilization (%)'],
                        availability_if_planned(M, flipped_all),
                    )
                ),
            }
        )
    table = pd.DataFrame(scenarios)
    table['Change in Availability (pp)'] = table['Availability (%)'] - M.availability
    return table


