def bootstrap_downtime(daily_hours, days, block_size=1, seed=SEED):
    """Total downtime hours over `days`, resampling `block_size`-day blocks of the daily series."""
    rng = np.random.default_rng(seed)
    values = daily_hours.dropna().to_numpy()
    block_size = max(1, min(block_size, len(values)))
    n_blocks = int(np.ceil(days / block_size))
    starts = rng.integers(0, len(values) - block_size + 1, size=(N_TRIALS, n_blocks))
    sampled = values[starts[:, :, None] + np.arange(block_size)].reshape(N_TRIALS, -1)[:, :days]
    return sampled.sum(axis=1)


def clustering_widening(daily_hours):
    """Spread of block-bootstrap totals relative to independent-day totals (at least 1)."""
    if len(daily_hours.dropna()) < 10 or daily_hours.std() == 0:
        return 1.0
    blocks = estimate_block_size(daily_hours)[0]
    independent = bootstrap_downtime(daily_hours, FORECAST_DAYS, 1).std()
    clustered = bootstrap_downtime(daily_hours, FORECAST_DAYS, blocks).std()
    return max(clustered / independent, 1.0) if independent > 0 else 1.0


def build_history(L, unit, window=None):
    """What the simulation needs from one unit's history: reasons, rate calibration, widening."""
    log = L.logs[unit]
    window = L.dfs[unit] if window is None else window
    per_day = scaled_class_hours(log, window['Duration (hours)'].sum()) / len(window)
    reasons = (
        log[log['Class'] == 'Unplanned loss']
        .groupby(['Reason', 'Waiting'], as_index=False)
        .agg(h=('Duration_hours', 'sum'), n=('Count', 'sum'))
    )
    reasons = reasons[reasons['h'] > 0].reset_index(drop=True)
    log_days = len(L.daily_full[unit])
    log_rate = reasons['h'].sum() / log_days
    return {
        'unit': unit,
        'log_days': log_days,
        'per_day': per_day,
        'reasons': reasons,
        'scale': (
            per_day['Unplanned loss'] / log_rate if CALIBRATE_TO_WINDOW and log_rate > 0 else 1.0
        ),
        'widen': clustering_widening(window['Duration (hours)']) if CLUSTERING_WIDENING else 1.0,
        'waiting_share': (
            (reasons.loc[reasons['Waiting'], 'h'].sum() / reasons['h'].sum())
            if len(reasons)
            else 0.0
        ),
    }


def simulate_groups(reasons, key, history, days, seed):
    """Unplanned hours over `days` per value of `key`: {group: array of N_TRIALS}.

    Reasons with hours but no event count are treated as a steady daily amount.
    """
    rng = np.random.default_rng(seed)
    sims = {group: np.zeros(N_TRIALS) for group in reasons[key].unique()}
    for group, hours, events in zip(reasons[key], reasons['h'], reasons['n']):
        if events > 0:
            counts = rng.poisson(
                events / history['log_days'] * history['scale'] * days, size=N_TRIALS
            )
            simulated = np.zeros(N_TRIALS)
            occurred = counts > 0
            simulated[occurred] = rng.gamma(
                shape=counts[occurred] * SHAPE, scale=(hours / events) / SHAPE
            )
            sims[group] += simulated
        else:
            sims[group] += hours / history['log_days'] * history['scale'] * days
    if history['widen'] != 1.0:
        sims = {
            g: np.clip(s.mean() + (s - s.mean()) * history['widen'], 0, None)
            for g, s in sims.items()
        }
    return sims


def simulate_unit(history, days, seed):
    """(own-fault and other hours, waiting hours) per trial, capped at the calendar."""
    sims = simulate_groups(history['reasons'], 'Waiting', history, days, seed)
    own, wait = sims.get(False, np.zeros(N_TRIALS)), sims.get(True, np.zeros(N_TRIALS))
    cap = np.where(own + wait > 24.0 * days, 24.0 * days / np.maximum(own + wait, 1e-9), 1.0)
    return own * cap, wait * cap


def unit_availability(own, wait, days, planned_other, planned_maintenance):
    """Availability with waiting as a loss, Availability with waiting left out (the unit when it was asked to run),
    and Calendar Availability, in % per trial."""
    base, planned_production = time_split(days, planned_other, planned_maintenance)
    loss, calendar_pct, _ = availability_pct(own + wait, base, planned_production)
    asked_to_run = np.maximum(planned_production - wait, 1e-9)
    return loss, np.clip((asked_to_run - own) / asked_to_run * 100, 0, 100), calendar_pct


