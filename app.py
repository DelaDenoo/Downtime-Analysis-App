def make_rules(extra=None):
    """BASE_RULES with a line's own wording added (extra = {rule name: [patterns]})."""
    extra = extra or {}
    unknown = set(extra) - set(BASE_RULES)
    assert not unknown, f'unknown rule names in rules_extra: {sorted(unknown)}'
    rules = {
        name: list(patterns) + list(extra.get(name, [])) for name, patterns in BASE_RULES.items()
    }
    assert all(
        re.compile(p).groups == 0 for patterns in rules.values() for p in patterns
    ), 'use (?: ) in patterns'
    return rules


def match_any(texts, patterns):
    if not patterns or texts.empty:
        return pd.Series(False, index=texts.index, dtype=bool)
    return texts.str.contains('|'.join(f'(?:{p})' for p in patterns), case=False, regex=True)


CLASSES = ['Unplanned loss', 'Planned non-production', 'Planned maintenance']


def classify_by_wording(reasons, rules):
    return pd.Series(
        np.select(
            [
                match_any(reasons, rules['unplanned_override']),
                match_any(reasons, rules['planned_maintenance']),
                match_any(reasons, rules['planned']),
            ],
            ['Unplanned loss', 'Planned maintenance', 'Planned non-production'],
            default='Unplanned loss',
        ),
        index=reasons.index,
    )

