def read_daily(book, usecols, skiprows, sheet=0):
    """Daily downtime hours of one unit for every valid date in the file (no month exclusion)."""
    daily = book.parse(sheet_name=sheet, usecols=usecols, skiprows=skiprows)
    title = str(daily.columns[1])
    daily.columns = ['Day', 'Duration (hours)']
    daily['Duration (hours)'] = pd.to_numeric(daily['Duration (hours)'], errors='coerce')
    daily['Date'] = pd.to_datetime(daily['Day'], errors='coerce')
    notes = {
        'date_without_hours': int((daily['Date'].notna() & daily['Duration (hours)'].isna()).sum()),
        'hours_without_date': int((daily['Date'].isna() & daily['Duration (hours)'].notna()).sum()),
    }
    daily = (
        daily.dropna(subset=['Date', 'Duration (hours)']).sort_values('Date').reset_index(drop=True)
    )
    daily.attrs.update(notes, title=title)
    return daily


