def line_findings(L):
    """Plain-language findings for one line, built from the tables above (run every report for the line first)."""
    findings = []
    window_text = {unit: f'{L.metrics[unit].days} days' for unit in L.headline}
    off_target = (
        L.results['log_checks']
        .loc[~L.results['log_checks']['Log / daily (%)'].between(95, 105), 'Unit']
        .tolist()
    )
    for unit in L.headline:
        M, name = L.metrics[unit], L.short[unit]
        scenarios = L.results['sensitivity'].query('Unit == @unit')['Availability (%)']
        findings.append(
            f'{name}, window {window_text[unit]}: Availability {M.availability:.1f}%, '
            f'Calendar Availability '
            f'{M.calendar_availability:.1f}%, Utilization {M.utilization:.1f}% (planned '
            f'maintenance '
            f'{PM_PHRASE[PLANNED_MAINTENANCE_HANDLING]}).'
        )
        findings.append(
            f'{name}: Availability moves between {scenarios.min():.1f}% and '
            f'{scenarios.max():.1f}% across the '
            'planned-share and borderline-reason scenarios.'
        )
        low, high = L.month_range[unit]
        findings.append(
            f'{name}: Calendar Availability by month ranges from {low:.1f}% to {high:.1f}%.'
        )
        reasons_to_80, n_reasons, waiting_pct = L.pareto_summary[unit]
        findings.append(
            f'{name}: {reasons_to_80} of {n_reasons} unplanned reasons make up 80% of '
            f'unplanned hours; '
            f'waiting is {waiting_pct:.0f}% of them.'
        )
        clear = L.clarity_pct[unit]['Clearly identified']
        findings.append(
            f'{name}: {clear:.0f}% of logged downtime is clearly described; '
            f'{100 - clear:.0f}% is vague, minor or unknown.'
        )
        base = L.results['headline_forecast'].query('Unit == @unit and Scenario == "Base"')
        if len(base):
            row = base.iloc[0]
            findings.append(
                f'{name}: {FORECAST_DAYS}-day Availability forecast (base planned time): '
                f'{row["Availability P10 (%)"]:.1f}% to {row["Availability P90 (%)"]:.1f}% '
                f'(P10 to P90).'
            )
        back = L.results['backtest_units']
        if len(back) and unit in back['Unit'].tolist():
            row = back[back['Unit'] == unit].iloc[0]
            findings.append(
                f'{name}: backtest of the last {int(row["Held-back days"])} days, unplanned '
                f'hours: actual '
                f'{row["Actual (scaled, hrs)"]:.1f} h against {row["Forecast P10"]:.1f} to '
                f'{row["Forecast P90"]:.1f} h '
                f'({row["Verdict"].lower()}).'
            )
    if L.reference:
        top, share, unresolved = L.top_source
        findings.append(
            f'From the {L.short[L.reference]} comments blamed on units: {top} is the '
            f'largest attributed source ({share:.0f}% of unplanned '
            f'hours); {unresolved:.0f}% cannot be tied to a unit.'
        )
    coverage = L.coverage
    vague = coverage[[c for c in coverage.columns if c.startswith('Vague')][0]]
    outside = coverage['Waiting or supply (%)']
    findings.append(
        f'From the units\' own logs by theme: the vague share (Unknown, Minor stops, Not '
        f'Clearly Identified) is highest for '
        f'{L.short[vague.idxmax()]} ({vague.max():.0f}%); waiting or supply is highest for '
        f'{L.short[outside.idxmax()]} ({outside.max():.0f}%).'
    )
    unit, month, value = L.worst_month
    findings.append(
        f'Lowest Calendar Availability of any unit in any month: {L.short[unit]} in '
        f'{month:%b %Y} ({value:.0f}%).'
    )
    findings.append(
        'Reason logs that do not reconcile with their daily column: '
        + (', '.join(off_target) if off_target else 'none')
        + '.'
    )
    print(f'{L.name}: summary of findings')
    print('\n'.join(f'{i}. {text}' for i, text in enumerate(findings, 1)))
    L.findings = findings

