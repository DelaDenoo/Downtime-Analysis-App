def compare_lines(lines):
    """One row per headline unit across all lines: the figures a plant-level reader wants side by side."""
    rows = []
    for L in lines:
        for unit in L.headline:
            M = L.metrics[unit]
            cov = L.coverage.loc[unit]
            rows.append(
                {
                    'Line': L.name,
                    'Unit': unit,
                    'Days': M.days,
                    'Availability (%)': M.availability,
                    'Calendar Availability (%)': M.calendar_availability,
                    'Utilization (%)': M.utilization,
                    'Planned (% of logged hrs)': cov['Planned (%)'],
                    'Waiting or supply (% of logged hrs)': cov['Waiting or supply (%)'],
                    'Vague (% of logged hrs)': cov[
                        [c for c in cov.index if c.startswith('Vague')][0]
                    ],
                    'Window downtime (hrs)': M.downtime,
                }
            )
    summary = pd.DataFrame(rows)
    display(summary.round(1))
    fig, ax = plt.subplots(figsize=(12, 0.5 * len(summary) + 2.5))
    y = np.arange(len(summary))
    ax.barh(
        y - 0.2, summary['Availability (%)'], height=0.38, color=COLOR['unit'], label='Availability'
    )
    ax.barh(
        y + 0.2,
        summary['Calendar Availability (%)'],
        height=0.38,
        color=COLOR['good'],
        label='Calendar Availability',
    )
    ax.set_yticks(
        y,
        [
            f'{L_name}: {u.split(": ")[-1].split(" (")[0]}'
            for L_name, u in zip(summary['Line'], summary['Unit'])
        ],
    )
    ax.invert_yaxis()
    ax.set_xlim(0, 105)
    ax.set_xlabel(
        '% (overall window figures; planned maintenance '
        + PM_PHRASE[PLANNED_MAINTENANCE_HANDLING]
        + ')'
    )
    ax.legend(loc='upper center', bbox_to_anchor=(0.5, -0.12), ncol=2)
    ax.set_title('Headline units across the plant: Availability and Calendar Availability')
    fig.tight_layout()
    safe_savefig(fig, 'plant_headline_units')
    plt.show()
    print(
        'Units on different lines are not like for like: each line has its own reference '
        'unit, its own planned-time'
    )
    print(
        'pattern (the moulding lines are often idle for lack of demand) and its own reason '
        'vocabulary.'
    )
    return summary


def export_results(lines, summary):
    """One workbook: a plant summary sheet, then every line's tables with the line tag as a prefix."""
    written = 0
    with pd.ExcelWriter(RESULTS_FILE) as writer:
        summary.to_excel(writer, sheet_name='Plant_summary', index=False)
        for L in lines:
            for name, table in L.results.items():
                if isinstance(table, pd.DataFrame) and len(table):
                    table.to_excel(writer, sheet_name=f'{L.tag}_{name}'[:31], index=False)
                    written += 1
            pd.DataFrame({'Finding': L.findings}).to_excel(
                writer, sheet_name=f'{L.tag}_findings'[:31], index=False
            )
    print(f'Wrote {written + len(lines) + 1} sheets to {RESULTS_FILE}; charts are in {SAVE_DIR}/')


